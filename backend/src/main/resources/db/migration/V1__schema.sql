CREATE TABLE outfits (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(40) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL,
 description TEXT, origin TEXT, cultural_meaning TEXT, thumbnail_url VARCHAR(255),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE colors (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(40) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL, hex_code VARCHAR(7) NOT NULL
);
CREATE TABLE accessories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(40) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL, type VARCHAR(40) NOT NULL,
 description TEXT, image_url VARCHAR(255), layer_order INTEGER NOT NULL
);
CREATE TABLE styles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(40) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL, description TEXT
);
CREATE TABLE events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(40) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL, description TEXT
);
CREATE TABLE outfit_assets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 outfit_id BIGINT NOT NULL REFERENCES outfits(id), color_id BIGINT NOT NULL REFERENCES colors(id),
 asset_type VARCHAR(40) NOT NULL, variant_code VARCHAR(40) NOT NULL,
 image_url VARCHAR(255), layer_order INTEGER NOT NULL,
 UNIQUE(outfit_id,color_id,asset_type,variant_code)
);
CREATE TABLE outfit_accessories (
 outfit_id BIGINT NOT NULL REFERENCES outfits(id), accessory_id BIGINT NOT NULL REFERENCES accessories(id),
 compatibility_score INTEGER CHECK (compatibility_score BETWEEN 0 AND 100),
 PRIMARY KEY(outfit_id,accessory_id)
);
CREATE TABLE cultural_rules (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 outfit_id BIGINT NOT NULL REFERENCES outfits(id),
 category VARCHAR(40) NOT NULL CHECK (category IN ('STRUCTURE','GARMENT_CHARACTERISTICS','ACCESSORIES','CONTEXT','MODERN_REMIX')),
 target_type VARCHAR(40) NOT NULL CHECK (target_type IN ('OUTFIT','COLOR','STYLE','EVENT','ACCESSORY')),
 target_code VARCHAR(40) NOT NULL,
 rule_type VARCHAR(40) NOT NULL CHECK (rule_type IN ('RECOMMENDED','CAUTION','INCOMPATIBLE')),
 score_modifier INTEGER NOT NULL CHECK (score_modifier BETWEEN -100 AND 100),
 severity VARCHAR(40) NOT NULL CHECK (severity IN ('LOW','MEDIUM','HIGH')),
 message TEXT NOT NULL, suggestion TEXT, source_name VARCHAR(255) NOT NULL, source_url TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_cultural_rules_outfit ON cultural_rules(outfit_id);
CREATE TABLE cultural_knowledge (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 outfit_id BIGINT NOT NULL REFERENCES outfits(id), category VARCHAR(40) NOT NULL,
 title VARCHAR(255) NOT NULL, content TEXT NOT NULL,
 source_name VARCHAR(255) NOT NULL, source_url TEXT NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_cultural_knowledge_outfit ON cultural_knowledge(outfit_id);
CREATE TABLE looks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 outfit_id BIGINT NOT NULL REFERENCES outfits(id), color_id BIGINT NOT NULL REFERENCES colors(id),
 style_id BIGINT NOT NULL REFERENCES styles(id), event_id BIGINT NOT NULL REFERENCES events(id),
 original_prompt TEXT, style_match_score INTEGER CHECK (style_match_score BETWEEN 0 AND 100),
 cultural_score INTEGER CHECK (cultural_score BETWEEN 0 AND 100),
 color_harmony_score INTEGER CHECK (color_harmony_score BETWEEN 0 AND 100),
 preview_image_url VARCHAR(2048),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE look_accessories (
 look_id BIGINT NOT NULL REFERENCES looks(id), accessory_id BIGINT NOT NULL REFERENCES accessories(id),
 PRIMARY KEY(look_id,accessory_id)
);
